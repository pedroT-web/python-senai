# Presença: Crie uma tupla chamada nomes contendo os nomes "Ana", "Carlos" e "Beatriz". 
# Verifique se o nome "Ana" está presente na tupla e se o nome "Maria" está presente na tupla, 
# utilizando o operador in.
nomes = ("Ana", "Carlos", "Beatriz")

if "Ana" in nomes:
    print("Ana está presente na lista")
else:
    print("Ana não está presente na lista")
    
if "Maria" in nomes:
    print("Maria está presente na lista")
else:
    print("Maria não está presente na lista")
