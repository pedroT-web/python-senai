# Encontrar o Maior e o Menor Elemento de uma Lista:
# Crie um programa que encontre o maior e o menor elemento de uma lista de números.
lista_numeros = [2, 5, 1, 10, 6, 19, 208]

maior = max(lista_numeros)
menor = min(lista_numeros)

print(f"O maior valor da lista é {maior} e o menor é {menor}")